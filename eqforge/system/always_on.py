"""Always-on routing: EQForge in the audio path *before* audio starts.

The problem this solves
-----------------------
In both deployments EQForge sits between an application and the speakers, and
the interesting question is *when* it gets into the path:

* **rt host** - applications are linked to the sink by WirePlumber the moment
  their stream node appears. Routing them through `eqforge-rt` is a rewrite
  of that decision, so it always happens *after* the first samples have
  already gone straight to the sink. The daemon minimises that window
  (registry events instead of a 2 s poll, see `eqforge.system.watch`), but
  it cannot make it zero: something has to react.
* **SPA filter node** - the node itself is resident from login, so a stream
  can be linked into it from its first sample. Zero by construction.

`always-on` therefore does the one thing a daemon cannot: it tells
WirePlumber, in WirePlumber's own policy language, that new playback streams
belong to EQForge. The stream is then *created* on EQForge's inputs - there is
no moment in which the first second of programme material takes a shortcut
around the processor.

    app stream created  ->  WirePlumber links it to eqforge  ->  sink

The daemon keeps its rewiring pass as a safety net (a rule can be shadowed by
another policy drop-in, and hot-plug redeployments happen), so the two
mechanisms layer: policy for "from the first sample", events for "whenever
reality disagrees with policy".

Scope and safety
----------------
* Only `Stream/Output/Audio` is matched. Microphones, MIDI, camera audio and
  other people's filter nodes are untouched.
* The target node must exist in the live graph before the rule is written -
  a rule pointing at a name nobody owns is how a user ends up with silent
  applications. `--node` overrides the auto-detected name.
* `off` removes the drop-in and restarts WirePlumber; the daemon's rewiring
  keeps working exactly as before, so nothing is lost but the zero-gap
  behaviour.
* WirePlumber >= 0.5 uses `node.rules` in a `.conf` drop-in. 0.4 needs the
  Lua scripting API (`packaging/wireplumber/50-eqforge.lua.example`, shipped
  with the repo); this module refuses on 0.4 instead of writing a file that
  the session would ignore.
"""
from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path

from eqforge.errors import SystemError
from eqforge.log import get_logger
from eqforge.system import module_config as mc
from eqforge.system import pipewire as pw

log = get_logger("system.always_on")

#: Node names, in the order they are preferred. `eqforge_filter` is the SPA
#: filter node (module deployment); `eqforge` is the rt host's JACK client.
DEFAULT_CANDIDATES = ("eqforge_filter", "eqforge")

RULE_TEMPLATE = """\
# EQForge always-on routing (generated by `eqforge system always-on on`).
#
# Every new application playback stream is created on EQForge's inputs instead
# of the default sink, so it is processed from its very first sample - there is
# no window in which the onset of playback bypasses the equalizer.
#
# Remove with `eqforge system always-on off` (or delete this file and
# `systemctl --user restart wireplumber`). `eqforge system always-on status`
# shows what is active.

node.rules = [
    {
        matches = [
            { media.class = "Stream/Output/Audio" }
        ]
        actions = {
            update-props = {
                target.object = "%(node)s"
            }
        }
    }
]
"""


def rule_file(home: Path | str | None = None) -> Path:
    """Where the generated WirePlumber drop-in lives."""
    base = Path(home) if home is not None else Path(os.path.expanduser("~"))
    return (base / ".config/wireplumber/wireplumber.conf.d"
            / "60-eqforge-streams.conf")


def render_rule(node: str) -> str:
    return RULE_TEMPLATE % {"node": node}


def wireplumber_version() -> tuple[int, int] | None:
    """Best-effort (major, minor) of the running WirePlumber, or None."""
    for cmd in (["wireplumber", "--version"], ["wpctl", "--version"]):
        try:
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=5)
        except (OSError, subprocess.TimeoutExpired):
            continue
        m = re.search(r"(\d+)\.(\d+)", (r.stdout or "") + (r.stderr or ""))
        if m:
            return int(m.group(1)), int(m.group(2))
    return None


def _supports_node_rules() -> bool:
    """WirePlumber >= 0.5 reads `node.rules` from a `.conf` drop-in."""
    ver = wireplumber_version()
    if ver is None:
        return True                 # unknown: assume modern, the rule is inert
    return ver >= (0, 5)


def detect_node() -> str | None:
    """The EQForge node actually present in the graph, if any."""
    if not pw.pipewire_available():
        return None
    try:
        view = pw.snapshot()
    except SystemError:
        return None
    for name in DEFAULT_CANDIDATES:
        if view.node_id(name) is not None:
            return name
    return None


def configured_node(path: Path | None = None) -> str | None:
    """The node name written into the drop-in, if it is installed."""
    p = path or rule_file()
    if not p.exists():
        return None
    m = re.search(r'target\.object\s*=\s*"([^"]+)"', p.read_text(errors="replace"))
    return m.group(1) if m else None


def _restart_wireplumber() -> tuple[bool, str]:
    try:
        r = subprocess.run(["systemctl", "--user", "restart", "wireplumber"],
                           capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.TimeoutExpired) as e:
        return False, str(e)
    return r.returncode == 0, (r.stderr or r.stdout or "").strip()[:200]


def enable(node: str | None = None, *, restart: bool = False,
           force: bool = False) -> dict:
    """Install the always-on routing rule.

    Returns a report dict; raises SystemError when the rule cannot be written
    safely (no node to target, or a WirePlumber that would ignore it).
    """
    if not _supports_node_rules() and not force:
        ver = wireplumber_version()
        raise SystemError(
            "WirePlumber %s does not read node.rules from a .conf drop-in" %
            (".".join(map(str, ver)) if ver else "(unknown version)"),
            hint="use the Lua policy in packaging/wireplumber/"
                 "50-eqforge.lua.example, or pass --force if your "
                 "WirePlumber does support node.rules")

    target = node or detect_node()
    if not target:
        raise SystemError(
            "no EQForge node in the audio graph to route streams to",
            hint="start processing first (`eqforge system start`, or enable "
                 "the SPA filter node), then re-run "
                 "`eqforge system always-on on`; `eqforge devices` shows "
                 "what the graph contains")
    if node and pw.pipewire_available():
        try:
            seen = pw.snapshot().node_id(node) is not None
        except SystemError:
            seen = True                        # cannot check; trust the user
        if not seen:
            raise SystemError(
                f"node {node!r} is not in the audio graph",
                hint="`eqforge devices` lists the nodes PipeWire knows about")

    path = rule_file()
    status, backup = mc.write_managed(path, render_rule(target))
    report = {"node": target, "file": str(path), "status": status,
              "backup": str(backup) if backup else None, "restarted": False,
              "error": None}
    if restart:
        ok, err = _restart_wireplumber()
        report["restarted"] = ok
        report["error"] = None if ok else err
    return report


def disable() -> dict:
    """Remove the always-on rule (the daemon's rewiring keeps working)."""
    path = rule_file()
    existed = path.exists()
    if existed:
        path.unlink()
    return {"file": str(path), "removed": existed}


def status(node: str | None = None) -> dict:
    """What `always-on` currently does, without changing anything."""
    path = rule_file()
    installed = path.exists()
    wanted = configured_node(path) if installed else None
    live = detect_node()
    return {
        "file": str(path),
        "installed": installed,
        "node": wanted,
        "node_present": bool(live and wanted and live == wanted),
        "live_node": live,
        "wireplumber": wireplumber_version(),
        "supported": _supports_node_rules(),
        "ok": bool(installed and wanted and live == wanted),
    }
